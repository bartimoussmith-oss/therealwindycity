#!/usr/bin/env python3
"""
watermark_scrubber.py — Detect and remove NotebookLM / Gemini watermarking.

What is (and isn't) watermarked:

* NotebookLM does NOT stamp user-uploaded sources (your transcripts, slides,
  agenda PDFs). What Google *does* brand are some of its own generated outputs —
  most visibly Audio Overviews, which can carry a "Made with NotebookLM" style
  mark, and generated slide/video imagery that may carry a NotebookLM or Gemini
  logo overlay.

This scrubber therefore does three things:

1. scan_text() / scrub_text() — remove NotebookLM / Gemini watermark strings
   from generated text artifacts (banners, footers, "generated by" lines,
   attribution lines the model may have written into a script).
2. scan_image() / scrub_image_file() — optional OpenCV redaction of a logo
   region (blur / pixelate / crop) in a slide or video frame image. Only runs
   when OpenCV is installed and explicitly opted in via --scrub-frames.
3. scrub_video_frames() — ffmpeg-assisted frame extraction/scrub/re-encode
   stub: declared, documented, and a hard no-op unless the environment has
   ffmpeg AND the caller passes --scrub-video. Never touches DRM-protected
   files; never strips copyright management information from works you do not
   own.

LEGAL / ETHICAL NOTICE
----------------------
Only scrub artifacts you created or that you hold redistribution rights for
(e.g. public government records published by the City of Cheyenne). Do not use
this to circumvent DRM, remove watermarks from copyrighted third-party
video/slides, or launder attribution you are legally required to keep. When in
doubt, scrub text only and flag frames for manual review.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

# Watermark / branding strings to detect and strip from generated text.
# Ordered longest-first so longer matches win. Case-insensitive.
WATERMARK_PATTERNS = [
    re.compile(r"made with notebooklm", re.I),
    re.compile(r"generated with notebooklm", re.I),
    re.compile(r"created with notebooklm", re.I),
    re.compile(r"produced with notebooklm", re.I),
    re.compile(r"notebooklm by google", re.I),
    re.compile(r"\bnotebooklm\b", re.I),
    re.compile(r"powered by gemini", re.I),
    re.compile(r"generated by gemini", re.I),
    re.compile(r"gemini by google", re.I),
    re.compile(r"\bgemini\b", re.I),
    re.compile(r"made by google", re.I),
    re.compile(r"a google product", re.I),
    re.compile(r"google\s*[-–]\s*(ai|gemini)", re.I),
]

# Whole-line banners commonly emitted alongside a watermark.
BANNER_PATTERNS = [
    re.compile(r"^\s*[-_*]{3,}\s*(made with|generated with|created with|powered by)\s+.*$", re.I),
    re.compile(r"^\s*notebooklm\s*[-–|:].*$", re.I),
    re.compile(r"^\s*gemini\s*[-–|:].*$", re.I),
]


@dataclass
class ScanResult:
    found: bool
    matches: list[str]
    lines: list[int]  # 1-based line numbers where watermark material appears


def scan_text(text: str) -> ScanResult:
    """Return where NotebookLM / Gemini watermark material appears in text."""
    matches: list[str] = []
    lines: list[int] = []
    for idx, line in enumerate(text.splitlines(), start=1):
        hit = False
        for pat in BANNER_PATTERNS + WATERMARK_PATTERNS:
            if pat.search(line):
                hit = True
                m = pat.search(line)
                if m:
                    matches.append(m.group(0))
                break
        if hit:
            lines.append(idx)
    return ScanResult(found=bool(lines), matches=matches, lines=lines)


def scrub_text(text: str) -> tuple[str, ScanResult]:
    """Remove watermark strings and banner lines from text.

    Returns (scrubbed_text, scan_result) where scan_result reports what was
    found before removal, so the manifest can record an honest audit trail.
    """
    result = scan_text(text)
    if not result.found:
        return text, result

    kept: list[str] = []
    for line in text.splitlines():
        if any(pat.search(line) for pat in BANNER_PATTERNS):
            continue  # drop whole banner lines
        scrubbed = line
        for pat in WATERMARK_PATTERNS:
            scrubbed = pat.sub("", scrubbed)
        # collapse double spaces left by removal, but keep the line
        scrubbed = re.sub(r"[ \t]{2,}", " ", scrubbed).strip()
        kept.append(scrubbed)
    return "\n".join(kept), result


IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".webp", ".bmp"}


def scan_image_file(path: Path) -> ScanResult:
    """Heuristic: filename-based watermark suspicion for image/slide files."""
    name = path.name.lower()
    suspicious = any(tok in name for tok in ("notebooklm", "gemini", "watermark", "branding"))
    return ScanResult(found=suspicious,
                      matches=["filename"] if suspicious else [],
                      lines=[])


def scrub_image_file(path: Path, method: str = "blur") -> bool:
    """Redact a suspected logo region in an image file.

    Requires OpenCV (cv2). Returns True if scrubbed, False if skipped
    (OpenCV missing or file not an image). No-op by default in this repo.
    """
    if path.suffix.lower() not in IMAGE_EXTENSIONS:
        return False
    try:
        import cv2  # type: ignore
    except ImportError:
        print(f"[watermark] frame scrub skipped: OpenCV not installed ({path})")
        return False

    img = cv2.imread(str(path))
    if img is None:
        return False
    h, w = img.shape[:2]
    # Heuristic: NotebookLM/Gemini logo overlays usually sit in a top corner.
    # Redact the top-right 12% band — tune per template if you know the logo box.
    if method == "blur":
        box = img[0:int(h * 0.12), int(w * 0.80):w]
        box = cv2.GaussianBlur(box, (0, 0), 25)
        img[0:int(h * 0.12), int(w * 0.80):w] = box
    elif method == "crop":
        img = img[int(h * 0.12):h, 0:w]
    cv2.imwrite(str(path), img)
    return True


def scrub_video_frames(video_path: Path, timestamps: list[str], method: str = "blur") -> bool:
    """Extract frames at ``timestamps`` (HH:MM:SS), scrub, optionally re-encode.

    Hard no-op unless ffmpeg is available AND this function is wired into a
    caller that passed --scrub-video. Deliberately does not attempt DRM
    bypass, stream decryption, or key extraction.
    """
    import shutil
    if shutil.which("ffmpeg") is None:
        print(f"[watermark] video scrub skipped: ffmpeg not installed ({video_path})")
        return False
    print(f"[watermark] video frame scrub is a declared no-op in this build "
          f"(opt in with --scrub-video): {video_path}")
    return False
