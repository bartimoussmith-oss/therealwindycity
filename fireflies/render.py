"""Markdown renderers: per-meeting briefs + corpus index.

Everything rendered is either source data or a method-tagged derived field
carrying verbatim quotes. The brief header states the evidence grade and the
extractive-only policy so no reader mistakes selection for invention.
"""
from __future__ import annotations


def _ts_link(url: str, ts: str) -> str:
    if not url or not ts or ":" not in ts:
        return ""
    try:
        h, m, s = (int(x) for x in ts.split(":"))
    except ValueError:
        return ""
    if "youtube.com" in url or "youtu.be" in url:
        sep = "&" if "?" in url else "?"
        return f"{url}{sep}t={h * 3600 + m * 60 + s}"
    return ""


def brief_markdown(rec: dict) -> str:
    L = []
    date = rec["date"] or "undated"
    L.append(f"# {rec['body_label']} — {date}")
    L.append("")
    L.append(f"*Meeting `{rec['meeting_id']}` · title: {rec['title']} · "
             f"clip ids: {', '.join(rec['clip_ids']) or '—'}*")
    L.append("")
    L.append("> Fireflies-style brief generated by `fireflies` (extractive & "
             "pattern-based only — every line below is either source data or a "
             "method-tagged selection from source text; nothing is paraphrased "
             "into new claims). Verify quotes: `python3 -m fireflies verify`.")
    L.append("")

    st = rec["stats"]
    L.append("## At a glance")
    L.append(f"- Words of record text: **{st['words']:,}** across {st['texts']} source text(s); "
             f"{st['segments']} timestamped caption segments")
    if st.get("asr_turns_unlabeled"):
        L.append(f"- Unlabeled speaker turns in captions: **{st['asr_turns_unlabeled']}** "
                 "(no diarization — turns are counted, not attributed)")
    L.append(f"- Agenda items: **{st['items']}** · actions/decisions captured: **{st['actions']}**")
    if rec["flags"]:
        L.append(f"- Flags: {', '.join(rec['flags'])}")
    if rec["urls"]:
        links = " · ".join(f"[{k}]({v})" for k, v in rec["urls"].items() if v)
        if links:
            L.append(f"- Record links: {links}")
    L.append("")

    if rec.get("attendance", {}).get("quote"):
        a = rec["attendance"]
        L.append("## Attendance (verbatim)")
        L.append(f"> {a['quote']}")
        L.append(f"*— {a['locator'].get('ref', '')}*")
        L.append("")

    ov = rec.get("overview", {})
    if ov.get("sentences"):
        L.append(f"## Overview (extractive — method `{ov['method']}`)")
        for s in ov["sentences"]:
            loc = s["locator"]
            tag = f"¶{loc['para']}" if loc.get("para") else f"@{loc.get('char', 0)}"
            L.append(f"- {s['sentence']} *({tag})*")
        L.append("")

    if rec.get("outline"):
        L.append("## Outline")
        L.append("| # | Item | Chapter (start–end) | Method / confidence | Link |")
        L.append("|---|------|---------------------|---------------------|------|")
        for i, o in enumerate(rec["outline"], 1):
            span = (f"{o['start']}–{o['end']}" if o.get("end") else o.get("start") or "—")
            link = ""
            yurl = rec["urls"].get("youtube", "")
            if yurl and o.get("start") and ":" in o["start"]:
                link = f"[▶ jump]({_ts_link(yurl, o['start'])})"
            elif o.get("deep_link"):
                link = f"[▶ granicus]({o['deep_link']})"
            conf = f"{o['method']} / {o['confidence']}" if o["method"] else "—"
            L.append(f"| {i} | {o['title'][:110]} | {span} | {conf} | {link} |")
        L.append("")

    if rec.get("items"):
        L.append("## Agenda items & supporting documents")
        for it in rec["items"]:
            head = f"### {it['item_id']} — {it['title'][:170]}"
            L.append(head)
            meta = [f"kind: {it['kind']}"]
            if it["reading"]:
                meta.append(f"reading: {it['reading']}")
            if it["number"]:
                meta.append(f"no.: {it['number']}")
            if it["item_no"]:
                meta.append(f"agenda no.: {it['item_no']}")
            if it["title_guess"]:
                meta.append("title derived from speech cue (verbatim cue below)")
            L.append("*" + " · ".join(meta) + "*")
            for q in it["quotes"]:
                loc = q["locator"]
                tag = loc.get("ts") or (f"¶{loc['para']}" if loc.get("para") else loc.get("ref", ""))
                L.append(f"- quote (`{q['method']}`): “{q['quote']}” *({tag})*")
            if it["expected_action"]:
                L.append(f"- expected ACTION (agenda): {it['expected_action']}")
            for d in it["docs"]:
                ref = d.get("url") or d.get("ref") or ""
                L.append(f"- supporting doc ({d.get('kind', '?')}): {d.get('title', '')} — {ref}")
            L.append("")

    if rec.get("actions"):
        L.append("## Decisions & actions (verbatim, pattern-tagged)")
        for a in rec["actions"]:
            loc = a["locator"]
            tag = loc.get("ts") or (f"¶{loc['para']}" if loc.get("para") else loc.get("ref", ""))
            who = f" · who: {a['who']}" if a["who"] else ""
            item = f" · {a['item_id']}" if a["item_id"] else ""
            L.append(f"- **{a['type']}**{who}{item}: “{a['quote']}” *({tag})*")
        L.append("")

    if rec.get("entities"):
        L.append("## Entities")
        for e in rec["entities"][:20]:
            ex = e.get("example", {}).get("quote", "")
            L.append(f"- {e['type']} **{e['value']}** ×{e['count']}"
                     + (f" — e.g. “{ex[:160]}”" if ex else ""))
        L.append("")

    if rec.get("keywords"):
        L.append("## Keywords (extractive)")
        L.append(", ".join(f"{k['term']} ({k['count']})" for k in rec["keywords"]))
        L.append("")

    srcs = ", ".join(f"`{s['ref']}`" for s in rec["sources"])
    L.append("---")
    L.append(f"*Sources: {srcs or 'none captured'}*")
    return "\n".join(L) + "\n"


def index_markdown(ledger: list, stats: dict) -> str:
    L = []
    L.append("# Meeting intelligence index — Fireflies-style ledger")
    L.append("")
    L.append("Generated by `python3 -m fireflies build`. Extractive & "
             "pattern-based only; every quote is verifiable with "
             "`python3 -m fireflies verify`.")
    L.append("")
    L.append(f"- Meetings: **{stats['meetings']}** ({stats['dated']} dated) · "
             f"{stats['date_min']} → {stats['date_max']}")
    L.append(f"- Bodies: {', '.join(stats['bodies'])}")
    L.append(f"- Agenda items: **{stats['items']}** · actions/decisions: **{stats['actions']}** "
             f"· words of record: **{stats['words']:,}**")
    L.append(f"- Meetings with timestamped captions: {stats['meetings_with_asr']} · "
             f"with local supporting docs: {stats['meetings_with_docs']}")
    L.append(f"- Tracked entities (ordinances/resolutions/statutes): {stats['entities']} "
             "→ `topics.json`")
    L.append("")
    L.append("| Date | Body | Items | Actions | ASR | Brief |")
    L.append("|------|------|------:|--------:|:---:|-------|")
    for rec in sorted(ledger, key=lambda r: (r["date"] or "9999", r["body"]), reverse=True):
        asr = "✓" if rec["stats"]["segments"] else ""
        L.append(f"| {rec['date'] or 'undated'} | {rec['body']} | {rec['stats']['items']} "
                 f"| {rec['stats']['actions']} | {asr} "
                 f"| [brief](../briefs/{rec['meeting_id']}.md) |")
    L.append("")
    L.append("Flat exports: `meetings.jsonl` (full derived ledger) · "
             "`agenda_tracker.csv` (one row per agenda item) · `topics.json`.")
    return "\n".join(L) + "\n"
